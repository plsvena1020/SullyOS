// 菜品品类标注 —— 给菜单里每道菜标一个像真实外卖平台的品类
// （主食/小吃/饮品/甜品/套餐/药品/用品…）。
//
// 背景：生成脚本原先品牌店全标「招牌推荐」、独立小店只标「招牌推荐/热销」，
// 详情页每道菜下方的小字品类看起来只有两三种，「不正常」。
// gen-shopping-data.mjs 再生数据时调用；存量数据由 scripts/recat-shopping-dishes.mjs 重标。
//
// 适用范围：仅美食外卖/奶茶饮品/甜品蛋糕（关键词归类）与医药健康（药品/用品）；
// 其余店铺（超市 OFF 真实商品分类、生鲜果蔬、鲜花绿植）原样保留原品类。
// 原始品类不是「招牌推荐/热销」的（如 OFF 商品的日用品/乳品分类）也原样保留。
const FOOD_CATS = new Set(['美食外卖', '奶茶饮品', '甜品蛋糕']);
// 本分类器产出的标签：重跑时这些标签会被重新归类（修正误标），其余外部标签原样保留
const OUR_CATS = new Set(['招牌推荐', '热销', '主食', '小吃', '饮品', '甜品', '套餐', '热菜', '药品', '用品']);

export function assignDishCat(shopCat, dishName, origCat) {
  const n = String(dishName || '');
  if (origCat && !OUR_CATS.has(origCat)) return origCat;

  if (shopCat === '医药健康') {
    if (/口罩|创可贴|体温计|消毒|棉签|纱布|碘伏/.test(n)) return '用品';
    if (/药|丸|颗粒|胶囊|口服液|含片|糖浆|软膏|滴眼|喷雾|风油精|藿香|板蓝根|阿胶|维生素|钙|益生菌|开塞露|金银花|片$|散$|露$/.test(n)) return '药品';
    return '招牌推荐';
  }

  if (!FOOD_CATS.has(shopCat)) return origCat;

  if (/套餐|组合/.test(n)) return '套餐';
  if (/可乐|雪碧|芬达|矿泉水|柠檬水|果汁|咖啡|拿铁|美式|摩卡|卡布|澳瑞白|冷萃|星冰乐|奶茶|奶昔|酸奶|豆浆|酸梅汤|杨枝甘露|百香果|四季春|奶盖|奶绿|茉莉|摇摇|冰沙|柠檬茶|鲜芋|烤奶|生椰|葡萄/.test(n) || /茶$/.test(n)) return '饮品';
  if (/蛋挞|蛋糕|冰淇淋|圣代|布丁|泡芙|曲奇|提拉米苏|千层|面包|吐司|麻薯|蛋黄酥|凤梨酥|甜筒|摩天脆脆|老婆饼|菠萝包|司康|脏脏包|半熟芝士|肉松小贝/.test(n)) return '甜品';
  if (/薯条|鸡块|鸡翅|鸡米花|鸡爪|炸鸡|原味鸡|薯饼|麦乐鸡|芝士球|烤羊肉串|烤韭菜|烤茄子|烤鸡翅|烤面筋|串|花甲|生蚝|韭菜|面筋|小食|沙拉|茶叶蛋|蒸饺|炖罐|凉拌|卤蛋|煎蛋|毛肚|虾滑|午餐肉|牛肉丸|金针菇|土豆|宽粉|番茄汤底|^加(?!州)|汤/.test(n)) return '小吃';
  if (/堡|巨无霸|不素之霸|麦香鱼|饭|面|披萨|饺|馄饨|云吞|粉|米线|刀削|馍|卷|粥|油条|烧饼|冒菜|麻辣拌|麻辣烫|香锅/.test(n)) return '主食';
  if (/酸菜鱼|水煮肉片|毛血旺|小炒|干锅|辣椒炒肉|咸鸭蛋蒸肉|手撕鸡|白切鸡|炒肉|炒蛋/.test(n)) return '热菜';
  return '招牌推荐';
}

/** 整批重标（返回新数组，每项浅拷贝并替换 cat） */
export function recatDishes(dishes, shopCatOf) {
  return dishes.map(d => ({ ...d, cat: assignDishCat(shopCatOf(d.shopId), d.name, d.cat) }));
}
